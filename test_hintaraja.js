const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
assert.match(html, /id="hintaraja" min="0" max="100" step="1"/);
const code = html.slice(html.indexOf("        const hintaraja ="), html.indexOf('        let lajitteluValimuisti;'));
const handlers = {};
const slider = {max: '100', valueAsNumber: 12, style: {setProperty() {}}, setAttribute() {}, addEventListener: (name, fn) => handlers.slider = fn};
const input = {value: '', removeAttribute() {}, setAttribute() {}, hasAttribute: () => false, addEventListener: (name, fn) => handlers[name] = fn};
let timer, renders = 0;
const context = {document: {getElementById: id => id === 'hintaraja' ? slider : input}, setTimeout: (fn, ms) => (timer = {fn, ms}), clearTimeout: () => {timer = null}, renderWindow: () => renders++, paivitaMittarit() {}, scrollDebounceTimer: 0, isShifting: false, isUserScrolling: false, startIndex: 0};
vm.runInNewContext(code, context);
handlers.slider();
assert.equal(input.value, '12,00');
assert.equal(renders, 0);
assert.equal(timer.ms, 200);
slider.valueAsNumber = 13;
handlers.slider();
assert.equal(input.value, '13,00');
timer.fn();
assert.equal(renders, 1);
input.value = '12,34';
handlers.input();
assert.equal(renders, 2);
handlers.blur();
assert.equal(input.value, '12,34');
console.log('Hintaraja OK');
